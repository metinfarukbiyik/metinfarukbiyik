export const messages: Record<Lang, Record<MessageKey, string>> = { tr, en };

export type T = (key: MessageKey) => string;

export const I18nContext = createContext<{ lang: Lang; t: T }>({ lang: 'tr', t: (k) => tr[k] });

export const useI18n = () => useContext(I18nContext);

export const makeT = (lang: Lang): T => (key) => messages[lang][key] ?? messages.tr[key] ?? key;

export const browserLang = (): Lang =>
  typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en';
